export type CharacterCategory = (typeof categoryOrder)[number];

const categories: Record<CharacterCategory, { label: string; items: readonly CardSeed[] }> = {
  profession: { label: "Професія", items: professions },
  health: { label: "Здоров’я", items: health },
  biology: { label: "Біологія", items: biology },
  phobia: { label: "Фобія", items: phobias },
  hobby: { label: "Хобі", items: hobbies },
  trait: { label: "Характер", items: traits },
  fact: { label: "Факт", items: facts },
  baggage: { label: "Багаж", items: baggage },
  special: { label: "Активна карта", items: specials },
};

export function pick<T>(items: readonly T[]): T {
  return items[Math.floor(Math.random() * items.length)]!;
}

function shuffle<T>(items: readonly T[]) {
  const result = [...items];
  for (let index = result.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(Math.random() * (index + 1));
    [result[index], result[swapIndex]] = [result[swapIndex]!, result[index]!];
  }
  return result;
}

function cardFromSeed(category: CharacterCategory, seed: CardSeed): CharacterCard {
  const [value, note, tone, action] = seed;
  return { category, label: categories[category].label, value, note, tone, ...(action ? { action } : {}) };
}

export function makeCard(category: CharacterCategory, exceptValue?: string): CharacterCard {
  const source = exceptValue
    ? categories[category].items.filter(([value]) => value !== exceptValue)
    : categories[category].items;
  return cardFromSeed(category, pick(source.length ? source : categories[category].items));
}

export function makeCharacter(): CharacterCard[] {
  return categoryOrder.map((category) => makeCard(category));
}

export function makeCharacters(count: number): CharacterCard[][] {
  const decks = Object.fromEntries(
    categoryOrder.map((category) => [category, shuffle(categories[category].items)]),
  ) as Record<CharacterCategory, CardSeed[]>;

  return Array.from({ length: count }, (_, playerIndex) =>
    categoryOrder.map((category) => {
      const deck = decks[category];
      return cardFromSeed(category, deck[playerIndex % deck.length]!);
    }),
  );
}

